import streamlit as st

# Título da aplicação
st.title("Minha Primeira Aplicação Streamlit")

# Cabeçalho
st.header("Bem-vindo ao Streamlit!")

# Subcabeçalho
st.subheader("Vamos aprender a criar aplicações web interativas")

# Subtítulo
st.markdown("### O que é Streamlit?")

# Texto generico
st.write("""
         Streamlit é uma biblioteca de código aberto em Python que permite 
         criar aplicações web interativas de forma rápida e fácil. 
         Com Streamlit, você pode transformar seus scripts Python em aplicativos web 
         sem precisar de conhecimentos avançados de desenvolvimento web.""")

# texto literal
st.text("Vamos começar a explorar o Streamlit juntos!")